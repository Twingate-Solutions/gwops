"""The web-app, TLS, JWKS, mismatch and housekeeping blocks of ``GET /status``.

Read-only and failure-contained: a block that cannot be built logs the error type and degrades
to a block marked ``computation_failed`` with that error type, so ``/status`` never answers
500 because of one of them.
"""

from dataclasses import asdict
from datetime import datetime
from typing import Any

import structlog

from gwops import webapp_readiness
from gwops.access import webapp_policy
from gwops.acme.runner import AcmeSnapshot
from gwops.api.app import GwopsDeps
from gwops.api.ownership import entry_owners
from gwops.certs.on_demand import state_tls_warning, tls_mode
from gwops.certs.public import KNOWN_ROOTS
from gwops.configmodel.schema import AcmeSettings, EffectiveState
from gwops.gateway_id import gateway_id_for
from gwops.kinds import WEBAPP
from gwops.reconciler.core import PublicCertStatus, ReconcileResult, RemoteWebApp

logger = structlog.get_logger(__name__)

_BROWSER_TRUST_NOTE = (
    "The X.509 CA is generated by gwops: browsers trust web apps served over TLS only after "
    "the operator installs that CA in their trust stores."
)


def _failed(block: str, exc: BaseException) -> dict[str, Any]:
    """The marker a degraded block carries; logs the error type only."""
    error_type = type(exc).__name__
    logger.warning("status.block_failed", block=block, error_type=error_type)
    return {"computation_failed": True, "error_type": error_type}


_STATE_UNAVAILABLE: dict[str, Any] = {"computation_failed": True, "error_type": "StateUnavailable"}


def _unmanaged_flags(app: RemoteWebApp, state: EffectiveState | None) -> list[str]:
    flags: list[str] = []
    if state is not None:
        if any(webapp_policy.is_trusted_header_name(n, state) for n in app.header_rewrite_names):
            flags.append("trusted_name_rewrite")
        if any(webapp_policy.is_denied_header_name(n) for n in app.header_rewrite_names):
            flags.append("invalid_rewrite")
    if "none" in (app.upstream_tls, app.downstream_tls):
        flags.append("plaintext_mode")
    return flags


def _automation_off_policy(deps: GwopsDeps, state: EffectiveState | None) -> dict[str, Any]:
    """Automation-owned web apps whose effective entry breaks the automation field policy."""
    entries: list[dict[str, Any]] = []
    if state is None:
        return {"entries": entries, **_STATE_UNAVAILABLE}
    try:
        owners = entry_owners(deps, WEBAPP)
        for entry in state.web_apps:
            if owners.get(entry.name) != "automation":
                continue
            violations = WEBAPP.automation_field_violations(entry, state)
            if violations:
                entries.append(
                    {
                        "name": entry.name,
                        "violations": [{"field": v.field, "reason": v.reason} for v in violations],
                    }
                )
    except Exception as exc:  # a status block must never fail the endpoint
        return {"entries": [], **_failed("automation_off_policy", exc)}
    return {"entries": entries, "computation_failed": False}


def _ca_generated(state: EffectiveState) -> bool:
    """Whether gwops generates the X.509 CA; never in public mode (``ca.x509`` is defaults)."""
    return state.public_tls is None and state.ca.x509.generate


def _readiness(
    deps: GwopsDeps, state: EffectiveState, last: ReconcileResult, gateway_id: str | None
) -> tuple[list[dict[str, Any]], str | None]:
    """The readiness entries and the error type when the computation failed."""
    failures: list[BaseException] = []
    try:
        # Taken on its own: a runner that raises costs one acme_failed:internal reason, not the
        # whole readiness computation.
        acme_snapshot, acme_snapshot_failed = webapp_readiness.acme_snapshot(deps.acme)
        entries = webapp_readiness.compute_readiness(
            state,
            last,
            # Public mode never reads the gwops leaf (and has none to read).
            None if state.public_tls is not None else deps.certs.leaf_sans(),
            ca_generated=_ca_generated(state),
            on_demand=state.ca.x509.on_demand_issuance,
            gateway_id=gateway_id,
            on_failure=failures.append,
            public=webapp_readiness.public_input(
                state, last, acme_snapshot, acme_snapshot_failed=acme_snapshot_failed
            ),
        )
    except Exception as exc:  # compute_readiness degrades itself; this covers a broken caller
        logger.error("status.readiness_unexpected_failure", exc_info=True)
        failures.append(exc)
        entries = webapp_readiness.unverifiable_entries(state)
    error_type = type(failures[0]).__name__ if failures else None
    if error_type is not None:
        logger.warning("status.readiness_failed", error_type=error_type)
    else:
        entries = _with_probe(deps, entries)
    return [asdict(entry) for entry in entries], error_type


def _with_probe(
    deps: GwopsDeps, entries: list[webapp_readiness.ReadinessEntry]
) -> list[webapp_readiness.ReadinessEntry]:
    """The entries with the upstream TLS probe merged in; all unverifiable if the merge fails."""
    probe = deps.probe
    if probe is None or not probe.enabled:
        return entries
    try:
        snapshot = probe.snapshot()
        return webapp_readiness.apply_probe(
            entries,
            snapshot.results,
            snapshot.unverifiable,
            failed=snapshot.failed,
            refused=snapshot.refused,
            last_batch_error=snapshot.last_batch_error,
        )
    except Exception as exc:  # a status block must never fail the endpoint
        logger.warning("status.probe_merge_failed", error_type=type(exc).__name__)
        return webapp_readiness.probe_failed_entries(entries)


def _web_apps_block(
    deps: GwopsDeps, state: EffectiveState | None, last: ReconcileResult | None
) -> dict[str, Any]:
    gateway_id = gateway_id_for(deps.registry.managed_ids(), state)
    remote = last.remote_web_apps if last is not None else None
    listed = remote is not None
    here = [app for app in remote if app.gateway_id == gateway_id] if remote is not None else []
    unmanaged = [app for app in here if not app.managed]
    declared = state.web_apps if state is not None else []
    browser_trust = (
        _BROWSER_TRUST_NOTE
        if state is not None
        and _ca_generated(state)
        and any(app.downstream.tls == "tls13" for app in declared)
        else None
    )
    readiness: list[dict[str, Any]] = []
    readiness_status = "tenant_unlisted"
    error: dict[str, Any] = {}
    if last is not None and last.remote_web_apps_error is not None:
        readiness_status, error = "computation_failed", {"error_type": last.remote_web_apps_error}
    elif listed and last is not None:
        if state is None:
            readiness_status, error = "computation_failed", {"error_type": "StateUnavailable"}
        else:
            readiness, error_type = _readiness(deps, state, last, gateway_id)
            if error_type is not None:
                readiness_status, error = "computation_failed", {"error_type": error_type}
            else:
                readiness_status = "ok"
    show_unserved = state is not None and not declared
    return {
        "counts": {
            "declared": len(declared),
            "managed_on_tenant": sum(app.managed for app in remote) if remote is not None else None,
            "unmanaged_on_this_gateway": len(unmanaged) if listed else None,
        },
        "warnings": list(last.webapp_warnings) if last is not None else [],
        "browser_trust": browser_trust,
        "unmanaged": (
            [
                {"name": app.name, "id": app.id, "flags": _unmanaged_flags(app, state)}
                for app in unmanaged
            ]
            if listed
            else None
        ),
        "unserved": (
            ([{"name": app.name, "id": app.id} for app in here] if show_unserved else [])
            if listed
            else None
        ),
        "automation_off_policy": _automation_off_policy(deps, state),
        "readiness_status": readiness_status,
        **error,
        "readiness": readiness,
    }


def web_apps_block(
    deps: GwopsDeps, state: EffectiveState | None, last: ReconcileResult | None
) -> dict[str, Any]:
    """The ``web_apps`` block: counts, warnings, browser trust, strays and readiness.

    ``counts.managed_on_tenant``, ``counts.unmanaged_on_this_gateway``, ``unmanaged`` and
    ``unserved`` are null when the last pass did not list the tenant. ``readiness_status`` is
    ``ok``, ``tenant_unlisted`` or ``computation_failed`` (with ``error_type``, also when the
    tenant was listed but the pass could not read the listing).
    """
    try:
        return _web_apps_block(deps, state, last)
    except Exception as exc:  # a status block must never fail the endpoint
        return {
            "counts": None,
            "warnings": [],
            "browser_trust": None,
            "unmanaged": None,
            "unserved": None,
            "automation_off_policy": {"entries": [], **_failed("web_apps", exc)},
            "readiness_status": "computation_failed",
            "readiness": [],
            **_failed("web_apps", exc),
        }


def gateway_mismatches_block(last: ReconcileResult | None) -> dict[str, dict[str, Any]]:
    """``tg.gateway_mismatches``: every kind's mismatch, report-only."""
    if last is None:
        return {}
    return {
        key: {"remote_gateway_id": m.remote_gateway_id, "corrected": m.corrected}
        for key, m in sorted(last.gateway_mismatches.items())
    }


def _iso(value: datetime | None) -> str | None:
    return value.isoformat() if value is not None else None


def _acme_fallback(
    status: PublicCertStatus,
    settings: AcmeSettings | None,
    *,
    state: str | None,
    error_code: str | None,
    error_excerpt: str | None,
    state_error: str | None,
    config_error: str | None,
    task_dead: bool = False,
) -> dict[str, Any]:
    """The ``acme`` entry of a certificate the runner's snapshot does not describe.

    Carries the same keys as an entry built from a snapshot; the history fields are null.
    """
    return {
        "state": state,
        "directory": settings.directory_url if settings is not None else None,
        "staging": settings.is_staging if settings is not None else None,
        "installed": status.generation is not None,
        "installed_at": None,
        "installed_serial": None,
        "last_attempt_at": None,
        "last_success_at": None,
        "next_attempt_at": None,
        "error_code": error_code,
        "error_excerpt": error_excerpt,
        "renewal_reason": None,
        "consecutive_failures": 0,
        "in_backoff": False,
        "retry_after": None,
        "last_crash": None,
        "permissions_problem": None,
        "task_dead": task_dead,
        "state_error": state_error,
        "config_error": config_error,
    }


def _acme_entry(
    status: PublicCertStatus,
    snapshot: AcmeSnapshot | None,
    settings: AcmeSettings | None,
    config_error: str | None,
    *,
    runner_error: str | None = None,
    snapshot_failure: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """``certs.public[].acme`` for one ``source: acme`` certificate.

    From the runner's snapshot when it holds the certificate. Without it the seed's directory
    is reported and the history fields are null; ``state`` is ``failed`` with ``error_code``
    ``internal`` when the runner is unavailable (`runner_error`, why it could not be built) or
    its snapshot could not be taken (`snapshot_failure`, which also sets ``computation_failed``
    and ``error_type``), ``failed`` with ``config`` while `config_error` is set, else ``null``.
    ``state_error`` (the runner's unusable ``state.json``), ``config_error`` (unusable DNS token
    file or ACME configuration) and ``runner_error`` are bounded text that never carries the
    token or its file contents. ``task_dead`` is the runner-level flag that its loop is not
    running; ``last_crash`` and ``permissions_problem`` come from the snapshot.
    """
    if snapshot_failure is not None:
        return (
            _acme_fallback(
                status,
                settings,
                state="failed",
                error_code="internal",
                error_excerpt=f"ACME runner snapshot failed ({snapshot_failure.get('error_type')})",
                state_error=None,
                config_error=config_error,
            )
            | snapshot_failure
        )
    cert = snapshot.get(status.name) if snapshot is not None else None
    state_error = snapshot.state_error if snapshot is not None else None
    task_dead = snapshot.task_dead if snapshot is not None else False
    if cert is not None:
        return {
            "state": cert.state.value,
            "directory": cert.directory,
            "staging": cert.staging,
            "installed": cert.installed,
            "installed_at": _iso(cert.installed_at),
            "installed_serial": cert.installed_serial,
            "last_attempt_at": _iso(cert.last_attempt_at),
            "last_success_at": _iso(cert.last_success_at),
            "next_attempt_at": _iso(cert.next_attempt_at),
            "error_code": cert.error_code.value if cert.error_code is not None else None,
            "error_excerpt": cert.error_excerpt,
            "renewal_reason": cert.renewal_reason,
            "consecutive_failures": cert.consecutive_failures,
            "in_backoff": cert.in_backoff,
            "retry_after": _iso(cert.retry_after),
            "last_crash": cert.last_crash,
            "permissions_problem": cert.permissions_problem,
            "task_dead": task_dead,
            "state_error": state_error,
            "config_error": config_error,
        }
    if runner_error is not None:
        return _acme_fallback(
            status,
            settings,
            state="failed",
            error_code="internal",
            error_excerpt=runner_error,
            state_error=state_error,
            config_error=config_error,
            task_dead=task_dead,
        )
    return _acme_fallback(
        status,
        settings,
        state="failed" if config_error is not None else None,
        error_code="config" if config_error is not None else None,
        error_excerpt=config_error,
        state_error=state_error,
        config_error=config_error,
        task_dead=task_dead,
    )


def _public_certs_block(
    deps: GwopsDeps, state: EffectiveState, last: ReconcileResult | None
) -> list[dict[str, Any]]:
    statuses = last.public_certs if last is not None and last.public_certs is not None else []
    snapshot: AcmeSnapshot | None = None
    acme_failure: dict[str, Any] | None = None
    runner_error: str | None = None
    if any(s.source == "acme" for s in statuses):
        if deps.acme is None:
            runner_error = "ACME runner unavailable: " + (
                deps.acme_unavailable or "it was not started"
            )
        else:
            try:
                snapshot = deps.acme.snapshot()
            except Exception as exc:  # one block never fails /status
                logger.error("status.acme_snapshot_failed", exc_info=True)
                acme_failure = _failed("certs.public.acme", exc)
    settings = state.public_tls.acme if state.public_tls is not None else None
    config_error = next(
        (
            e.detail
            for e in (last.acme_errors if last is not None else [])
            if e.certificate is None and e.code == "config"
        ),
        None,
    )
    entries: list[dict[str, Any]] = []
    for status in statuses:
        entry: dict[str, Any] = {
            "name": status.name,
            "names": list(status.names),
            "not_after": _iso(status.not_after),
            "state": status.state,
            "last_error": status.last_error,
            "generation": status.generation,
        }
        if status.source == "acme":
            entry["acme"] = _acme_entry(
                status,
                snapshot,
                settings,
                config_error,
                runner_error=runner_error,
                snapshot_failure=acme_failure,
            )
        entries.append(entry)
    return entries


def _public_acme_errors(last: ReconcileResult | None) -> list[dict[str, str]]:
    """``certs.public_acme_errors``: ACME problems that name no certificate and are not ``config``.

    The runner being unavailable, its unusable state file, its dead task or any other
    certificate-less error the last pass recorded. ``config`` problems (token file, ACME
    configuration) are on each certificate's ``acme.config_error`` instead.
    """
    if last is None:
        return []
    return [
        {"code": e.code, "detail": e.detail}
        for e in last.acme_errors
        if e.certificate is None and e.code != "config"
    ]


def _registered_root_block(state: EffectiveState, last: ReconcileResult | None) -> dict[str, Any]:
    assert state.public_tls is not None
    root = last.registered_root if last is not None else None
    if root is None:
        name = state.public_tls.registered_root
        return {"name": name, "sha256": KNOWN_ROOTS[name], "tg_ca_id": None, "bound": None}
    return {
        "name": root.name,
        "sha256": root.sha256,
        "tg_ca_id": root.tg_ca_id,
        "bound": root.bound,
    }


def certs_block(
    deps: GwopsDeps, state: EffectiveState | None, sans: set[str], last: ReconcileResult | None
) -> dict[str, Any]:
    """The ``certs`` block: expiry and leaf state, plus ``public`` and ``registered_root``.

    In public mode ``x509_ca_not_after``, ``leaf_not_after`` and ``leaf_state`` are null (the
    leaf is never read) and ``public[]``, ``public_acme_errors[]`` (``{code, detail}``: ACME
    problems that name no certificate, other than ``config``) and ``registered_root`` are
    present; in private mode those three keys are absent. A failure degrades the whole block to
    ``{"computation_failed": true, "error_type": ...}``.
    """
    try:
        if state is not None and state.public_tls is not None:
            return {
                "x509_ca_not_after": None,
                "leaf_not_after": None,
                "leaf_state": None,
                "public": _public_certs_block(deps, state, last),
                "public_acme_errors": _public_acme_errors(last),
                "registered_root": _registered_root_block(state, last),
            }
        leaf = deps.certs.leaf_status(sans)
        return {
            "x509_ca_not_after": _iso(deps.certs.x509_ca_not_after()),
            "leaf_not_after": _iso(leaf.not_after),
            "leaf_state": leaf.state.value,
        }
    except Exception as exc:  # a status block must never fail the endpoint
        return _failed("certs", exc)


def tls_block(state: EffectiveState | None) -> dict[str, Any]:
    """The ``tls`` block: certificate mode and the on-demand exposure warning."""
    if state is None:
        return {"mode": None, "warning": None, **_STATE_UNAVAILABLE}
    try:
        return {"mode": tls_mode(state), "warning": state_tls_warning(state)}
    except Exception as exc:  # a status block must never fail the endpoint
        return {"mode": None, "warning": None, **_failed("tls", exc)}


def jwks_block(deps: GwopsDeps) -> dict[str, Any] | None:
    """The ``jwks`` block, or None when no monitor is wired or it has not checked yet."""
    status = deps.jwks.status if deps.jwks is not None else None
    if status is None:
        return None
    return {
        "ok": status.ok,
        "checked_at": status.checked_at.isoformat(),
        "error_class": status.error_class,
        "reason": status.reason,
    }


def housekeeping_block(last: ReconcileResult | None) -> dict[str, Any]:
    """The ``housekeeping`` block: failed cleanup steps and whether the last pass ran them."""
    if last is None:
        return {"errors": [], "ran": False}
    return {"errors": list(last.housekeeping_errors), "ran": last.housekeeping_ran}
